#!/usr/bin/env node
/**
 * Parses image-search stdout dumps (which contain log lines before the JSON)
 * and generates a TypeScript image map: src/data/image-map.ts
 *
 * Usage: node scripts/build-image-map.js
 */
const fs = require("fs");
const path = require("path");

const IMG_DIR = "/tmp/karto-imgs";
const OUT = path.join(__dirname, "..", "src", "data", "image-map.ts");

const CATEGORIES = [
  "fruits", "vegetables", "dairy", "snacks", "beverages", "bakery",
  "personal-care", "baby-care", "cleaning", "frozen", "instant",
  "medicines", "pet-care", "electronics", "home",
];

const map = {};
const categoryImages = {};

for (const cat of CATEGORIES) {
  const file = path.join(IMG_DIR, `${cat}.json`);
  let raw = "";
  try {
    raw = fs.readFileSync(file, "utf-8");
  } catch {
    console.warn(`Missing: ${cat}.json`);
    map[cat] = [];
    categoryImages[cat] = "";
    continue;
  }
  // Extract JSON starting at first '{'
  const start = raw.indexOf("{");
  if (start === -1) {
    console.warn(`No JSON in ${cat}.json`);
    map[cat] = [];
    categoryImages[cat] = "";
    continue;
  }
  const jsonStr = raw.slice(start);
  let urls = [];
  try {
    const data = JSON.parse(jsonStr);
    urls = (data.results || []).map((r) => r.original_url).filter(Boolean);
  } catch (e) {
    console.warn(`Parse error in ${cat}.json: ${e.message}`);
  }
  map[cat] = urls;
  categoryImages[cat] = urls[0] || "";
  console.log(`${cat}: ${urls.length} images`);
}

// Build the TS file
const ts = `// AUTO-GENERATED by scripts/build-image-map.js — real product photos from web image search.
// Do not edit by hand. Re-run the script after refreshing image searches.

export const categoryImages: Record<string, string> = ${JSON.stringify(categoryImages, null, 2)};

export const productImagesByCategory: Record<string, string[]> = ${JSON.stringify(map, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log(`\nWrote ${OUT}`);
